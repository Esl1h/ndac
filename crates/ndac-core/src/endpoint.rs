//! Configuration text for devices and resolvers that use a profile.
//!
//! Everything here only produces text: nothing is installed or run.
//! Formats follow the NextDNS setup instructions and the `nextdns` client
//! source; see `docs/src/endpoint.md` for sources and limits.

use std::fmt::Write as _;

use crate::config::Workspace;

/// IPv4 anycast addresses of NextDNS, used with the profile hostname as TLS
/// server name. IPv6 addresses are specific to each profile and not
/// available from the documented API, so they are left out.
pub const ANYCAST_V4: [&str; 2] = ["45.90.28.0", "45.90.30.0"];

/// Domain under which each profile has a DNS-over-TLS hostname.
pub const DOT_DOMAIN: &str = "dns.nextdns.io";

/// DNS-over-HTTPS base URL.
pub const DOH_BASE: &str = "https://dns.nextdns.io";

/// What to render.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Target {
    /// `/etc/nextdns.conf` for the `nextdns` client.
    NextdnsCli,
    /// A systemd-resolved drop-in using DNS over TLS.
    Resolved,
    /// `nmcli` commands for NetworkManager with systemd-resolved.
    NetworkManager,
    /// The Android "Private DNS" hostname.
    Android,
    /// The DNS-over-HTTPS URL.
    DohUrl,
}

/// Why a configuration cannot be rendered.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{0}")]
pub struct EndpointError(String);

fn fail(msg: impl Into<String>) -> EndpointError {
    EndpointError(msg.into())
}

/// The DNS-over-TLS hostname: `<device>-<id>.dns.nextdns.io`, where spaces
/// in the device name become `--`.
///
/// # Errors
///
/// A device name with characters other than ASCII letters, digits, `-` and
/// spaces, or too long for a DNS label.
pub fn dot_host(id: &str, device: Option<&str>) -> Result<String, EndpointError> {
    let Some(device) = device else {
        return Ok(format!("{id}.{DOT_DOMAIN}"));
    };
    let device = device.trim();
    if device.is_empty()
        || !device
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == ' ')
    {
        return Err(fail(format!(
            "device name {device:?}: only ASCII letters, digits, `-` and spaces can be used in a DNS-over-TLS hostname"
        )));
    }
    let label = format!("{}-{id}", device.replace(' ', "--"));
    if label.len() > 63 {
        return Err(fail(format!(
            "device name {device:?} is too long: `{label}` exceeds 63 characters"
        )));
    }
    Ok(format!("{label}.{DOT_DOMAIN}"))
}

/// Percent-encodes everything but RFC 3986 unreserved characters.
fn encode_segment(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for b in s.bytes() {
        if b.is_ascii_alphanumeric() || matches!(b, b'-' | b'.' | b'_' | b'~') {
            out.push(char::from(b));
        } else {
            let _ = write!(out, "%{b:02X}");
        }
    }
    out
}

/// The DNS-over-HTTPS URL: `https://dns.nextdns.io/<id>[/<device>]`, with
/// the device name URL-encoded.
#[must_use]
pub fn doh_url(id: &str, device: Option<&str>) -> String {
    match device.map(str::trim).filter(|d| !d.is_empty()) {
        Some(d) => format!("{DOH_BASE}/{id}/{}", encode_segment(d)),
        None => format!("{DOH_BASE}/{id}"),
    }
}

/// A value safe on a `nextdns.conf` line: no whitespace, `=` or `#`.
fn conf_value(what: &str, v: &str) -> Result<(), EndpointError> {
    if v.is_empty() || v.chars().any(|c| c.is_whitespace() || c == '#' || c == '=') {
        return Err(fail(format!(
            "endpoint {what} {v:?} cannot contain spaces, `=` or `#`"
        )));
    }
    Ok(())
}

fn is_profile_id(s: &str) -> bool {
    !s.is_empty()
        && s.bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
}

fn nextdns_conf(ws: &Workspace, key: &str, id: &str) -> Result<String, EndpointError> {
    let endpoint = ws
        .profiles
        .get(key)
        .and_then(|e| e.file.endpoint.clone())
        .unwrap_or_default();
    let mut out = format!(
        "# nextdns client configuration for profile \"{key}\" ({id}).\n\
         # Install as /etc/nextdns.conf, or pass the same options to\n\
         # `nextdns install`. Generated by ndac; review before installing.\n"
    );
    // The client uses the first matching profile line, so conditional
    // profiles come before the default.
    for (selector, target) in &endpoint.conditional {
        conf_value("conditional selector", selector)?;
        let target_id = match ws.profiles.get(target) {
            Some(e) => e.file.id.clone().filter(|i| !i.is_empty()).ok_or_else(|| {
                fail(format!(
                    "endpoint.conditional: profile \"{target}\" has no `id` yet; apply it first"
                ))
            })?,
            None if is_profile_id(target) => target.clone(),
            None => {
                return Err(fail(format!(
                    "endpoint.conditional: {target:?} is neither a profile key nor a profile ID"
                )));
            }
        };
        let _ = writeln!(out, "profile {selector}={target_id}");
    }
    let _ = writeln!(out, "profile {id}");
    if let Some(size) = &endpoint.cache_size {
        conf_value("cacheSize", size)?;
        let _ = writeln!(out, "cache-size {size}");
    }
    if let Some(report) = endpoint.report_client_info {
        let _ = writeln!(out, "report-client-info {report}");
    }
    Ok(out)
}

fn resolved(key: &str, id: &str, host: &str) -> String {
    let mut out = format!(
        "# systemd-resolved drop-in for NextDNS profile \"{key}\" ({id}), DNS over TLS.\n\
         # Install as /etc/systemd/resolved.conf.d/nextdns.conf, then run\n\
         # `systemctl restart systemd-resolved`. Generated by ndac; review first.\n\
         # IPv6 servers are left out: their addresses are specific to each\n\
         # profile and shown on its setup page in the NextDNS dashboard.\n\
         [Resolve]\n"
    );
    for ip in ANYCAST_V4 {
        let _ = writeln!(out, "DNS={ip}#{host}");
    }
    out.push_str("DNSOverTLS=yes\n");
    out
}

fn network_manager(key: &str, id: &str, host: &str) -> String {
    let servers: Vec<String> = ANYCAST_V4.iter().map(|ip| format!("{ip}#{host}")).collect();
    format!(
        "#!/bin/sh\n\
         # NetworkManager settings for NextDNS profile \"{key}\" ({id}), DNS over TLS.\n\
         # Requires NetworkManager with systemd-resolved as its DNS backend.\n\
         # Generated by ndac; review before running.\n\
         set -eu\n\
         CONNECTION=\"${{CONNECTION:?set CONNECTION to a name listed by nmcli connection show}}\"\n\
         nmcli connection modify \"$CONNECTION\" \\\n\
         \x20 ipv4.dns \"{}\" \\\n\
         \x20 ipv4.ignore-auto-dns yes \\\n\
         \x20 connection.dns-over-tls yes\n\
         nmcli connection up \"$CONNECTION\"\n",
        servers.join(" ")
    )
}

/// Renders `target` for the profile `key`.
///
/// # Errors
///
/// Unknown profile, a profile without `id`, or values that cannot be
/// written in the target format.
pub fn render(
    ws: &Workspace,
    key: &str,
    target: Target,
    device: Option<&str>,
) -> Result<String, EndpointError> {
    let entry = ws
        .profiles
        .get(key)
        .ok_or_else(|| fail(format!("unknown profile `{key}`")))?;
    let id = entry
        .file
        .id
        .as_deref()
        .filter(|i| !i.is_empty())
        .ok_or_else(|| fail(format!("profile \"{key}\" has no `id` yet; apply it first")))?;
    match target {
        Target::NextdnsCli => {
            if device.is_some() {
                return Err(fail(
                    "--device does not apply to the nextdns client; set `endpoint.reportClientInfo = true` to send device names",
                ));
            }
            nextdns_conf(ws, key, id)
        }
        Target::Resolved => Ok(resolved(key, id, &dot_host(id, device)?)),
        Target::NetworkManager => Ok(network_manager(key, id, &dot_host(id, device)?)),
        Target::Android => Ok(format!("{}\n", dot_host(id, device)?)),
        Target::DohUrl => Ok(format!("{}\n", doh_url(id, device))),
    }
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;

    fn workspace() -> (tempfile::TempDir, Workspace) {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path().join("ndac.toml");
        fs::write(&root, "schema = 1\ninclude = [\"profiles/*.toml\"]\n").unwrap();
        fs::create_dir_all(dir.path().join("profiles")).unwrap();
        fs::write(
            dir.path().join("profiles/casa.toml"),
            "id = \"abc123\"\n\n[endpoint]\ncacheSize = \"10MB\"\nreportClientInfo = true\n\n[endpoint.conditional]\n\"10.0.3.0/24\" = \"kids\"\n\"00:1c:42:2e:60:4a\" = \"fed987\"\n",
        )
        .unwrap();
        fs::write(dir.path().join("profiles/kids.toml"), "id = \"def456\"\n").unwrap();
        fs::write(dir.path().join("profiles/novo.toml"), "name = \"Novo\"\n").unwrap();
        let ws = Workspace::load(&root).unwrap();
        (dir, ws)
    }

    #[test]
    fn dot_hostnames() {
        assert_eq!(dot_host("abc123", None).unwrap(), "abc123.dns.nextdns.io");
        assert_eq!(
            dot_host("abc123", Some("John Router")).unwrap(),
            "John--Router-abc123.dns.nextdns.io"
        );
        assert_eq!(
            dot_host("abc123", Some("Note20")).unwrap(),
            "Note20-abc123.dns.nextdns.io"
        );
        assert!(dot_host("abc123", Some("John's")).is_err());
        assert!(dot_host("abc123", Some(&"x".repeat(60))).is_err());
    }

    #[test]
    fn doh_urls() {
        assert_eq!(doh_url("abc123", None), "https://dns.nextdns.io/abc123");
        assert_eq!(
            doh_url("abc123", Some("John's Firefox")),
            "https://dns.nextdns.io/abc123/John%27s%20Firefox"
        );
        assert_eq!(
            doh_url("abc123", Some("Café")),
            "https://dns.nextdns.io/abc123/Caf%C3%A9"
        );
    }

    #[test]
    fn nextdns_cli() {
        let (_d, ws) = workspace();
        let text = render(&ws, "casa", Target::NextdnsCli, None).unwrap();
        assert!(
            text.ends_with(
                "profile 00:1c:42:2e:60:4a=fed987\nprofile 10.0.3.0/24=def456\nprofile abc123\ncache-size 10MB\nreport-client-info true\n"
            ),
            "{text}"
        );
        assert!(render(&ws, "casa", Target::NextdnsCli, Some("x")).is_err());
        assert_eq!(
            render(&ws, "kids", Target::NextdnsCli, None)
                .unwrap()
                .lines()
                .last(),
            Some("profile def456")
        );
    }

    #[test]
    fn resolved_and_network_manager() {
        let (_d, ws) = workspace();
        let text = render(&ws, "casa", Target::Resolved, Some("Laptop")).unwrap();
        assert!(
            text.ends_with(
                "[Resolve]\nDNS=45.90.28.0#Laptop-abc123.dns.nextdns.io\nDNS=45.90.30.0#Laptop-abc123.dns.nextdns.io\nDNSOverTLS=yes\n"
            ),
            "{text}"
        );
        let nm = render(&ws, "casa", Target::NetworkManager, None).unwrap();
        assert!(
            nm.contains(
                "  ipv4.dns \"45.90.28.0#abc123.dns.nextdns.io 45.90.30.0#abc123.dns.nextdns.io\" \\\n"
            ),
            "{nm}"
        );
        assert!(nm.starts_with("#!/bin/sh\n"));
    }

    #[test]
    fn android_and_doh() {
        let (_d, ws) = workspace();
        assert_eq!(
            render(&ws, "casa", Target::Android, Some("Pixel 8")).unwrap(),
            "Pixel--8-abc123.dns.nextdns.io\n"
        );
        assert_eq!(
            render(&ws, "casa", Target::DohUrl, Some("Pixel 8")).unwrap(),
            "https://dns.nextdns.io/abc123/Pixel%208\n"
        );
    }

    #[test]
    fn errors() {
        let (_d, ws) = workspace();
        let e = render(&ws, "novo", Target::Android, None).unwrap_err();
        assert!(e.0.contains("no `id` yet"), "{e}");
        assert!(render(&ws, "nope", Target::Android, None).is_err());
        assert!(conf_value("cacheSize", "10 MB").is_err());
    }
}
